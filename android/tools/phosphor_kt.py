"""
Phosphor SVGs → `ui/common/Ph.kt`, the app's icon set.

The icons are Phosphor (MIT, https://phosphoricons.com), from the npm package
`@phosphor-icons/core` — only the ones the app draws, one folder per weight:

    <dir>/regular/<name>.svg    chrome: header, composer, menus
    <dir>/fill/<name>.svg       small marks: habit coins, project icons
    <dir>/bold/<name>.svg       glyphs under ~12dp: ticks, carets, close

Each file is one `<path>` on a 256 grid. To add an icon, fetch it into the
folder for its weight (https://cdn.jsdelivr.net/npm/@phosphor-icons/core@2/assets/<weight>/<name>[-<weight>].svg)
and rerun:

    python3 tools/phosphor_kt.py <dir>
"""
import pathlib
import re
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / 'app/src/main/java/com/sonu/spica/ui/common/Ph.kt'
WEIGHTS = [('regular', 'Ph', 'Regular weight — the chrome.'),
           ('fill', 'PhFill', 'Fill weight — marks drawn small, where an outline would be a smudge.'),
           ('bold', 'PhBold', 'Bold weight — glyphs under ~12dp.')]


KEYWORDS = {'package', 'object', 'class', 'fun', 'val', 'var', 'in', 'is', 'as', 'when', 'if', 'else', 'return', 'null', 'true', 'false', 'for', 'while', 'do', 'try', 'throw', 'this', 'super', 'typealias', 'interface'}


def camel(name: str) -> str:
    """Kotlin name for a Phosphor name; a keyword (`package`) is backticked."""
    head, *rest = name.split('-')
    n = head + ''.join(p.capitalize() for p in rest)
    return f'`{n}`' if n in KEYWORDS else n


def main(src: pathlib.Path) -> None:
    out = ['package com.sonu.spica.ui.common', '',
           'import androidx.compose.ui.graphics.Color',
           'import androidx.compose.ui.graphics.SolidColor',
           'import androidx.compose.ui.graphics.vector.ImageVector',
           'import androidx.compose.ui.graphics.vector.addPathNodes',
           'import androidx.compose.ui.unit.dp', '',
           '/*',
           ' * Phosphor icons (MIT, phosphoricons.com; licence in assets/licenses).',
           ' * Generated by android/tools/phosphor_kt.py — do not edit by hand.',
           ' */', '']
    for folder, obj, doc in WEIGHTS:
        files = sorted((src / folder).glob('*.svg'))
        if not files:
            continue
        out.append(f'/** {doc} */')
        out.append(f'object {obj} {{')
        names = []
        for f in files:
            svg = f.read_text()
            paths = re.findall(r'<path d="([^"]+)"', svg)
            if len(paths) != 1 or 'viewBox="0 0 256 256"' not in svg:
                raise SystemExit(f'{f}: expected one path on a 256 grid')
            n = f.stem
            names.append(n)
            out.append(f'    val {camel(n)}: ImageVector by lazy {{ vector("{n}", "{paths[0]}") }}')
        out.append('')
        out.append('    /** By Phosphor name — for icon keys that live in data (a tool, a section, a project). */')
        out.append('    fun of(name: String): ImageVector? = when (name) {')
        for n in names:
            out.append(f'        "{n}" -> {camel(n)}')
        out.append('        else -> null')
        out.append('    }')
        out.append('}')
        out.append('')
    out += ['private fun vector(name: String, d: String): ImageVector =',
            '    ImageVector.Builder(name, 24.dp, 24.dp, 256f, 256f)',
            '        .addPath(pathData = addPathNodes(d), fill = SolidColor(Color.Black))',
            '        .build()', '']
    OUT.write_text('\n'.join(out))
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main(pathlib.Path(sys.argv[1]))
